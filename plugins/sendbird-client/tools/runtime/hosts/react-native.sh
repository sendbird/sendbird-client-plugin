#!/usr/bin/env bash
# React Native host driver for tools/runtime/run.sh (--host react-native --platform ios|android).
# Called with the RT_* environment run.sh exports. A React Native app ships its native projects in
# ios/ and android/, so it runs on the same drivers as native apps (hosts/ios.sh, hosts/android.sh):
# their UI tests find the screen's elements through accessibility, which React Native fills in
# (text, button roles, testID as the iOS accessibility identifier). On the working copy:
#   1. npm install: the native builds read React Native and its native modules from node_modules
#   2. sign-in: an app with its own sign-in form is signed in through it by the UI test, as on iOS
#      and Android (lib/signin-form.sh rn). Otherwise the entry a release build bundles (index.js) is
#      wrapped: the wrapper runs the app's own entry, then calls the app's onLoginSucceeded(userId) a
#      moment later, as a sign-in screen would. The user ID is written into the wrapper: the release
#      build bundles the JavaScript at build time, and each run builds its own copy
#   3. hands over to hosts/ios.sh or hosts/android.sh with RT_RN=1, which build the app as a release
#      build with the JavaScript bundled in (no Metro server to start, keep running, or reach from
#      the device) and run the same UI test and user B as for native apps
# Exit 0 = driver finished (steps.jsonl says pass/fail), 1 = failed, 2 = skipped (prints SKIP: ...).
set -uo pipefail
work="$RT_WORK"; out="$RT_OUT"
step() { jq -nc --arg s "$1" --argjson ok "$2" --arg d "$3" '{step:$s, ok:$ok, detail:$d, screenshot:null}' >> "$out/steps.jsonl"; echo "step $1: $([ "$2" = true ] && echo ok || { [ "$2" = null ] && echo n/a || echo FAIL; }) — $3"; }

case "${RT_PLATFORM:-}" in ios|android) ;; *) echo "SKIP: --platform ios or android is required for react-native"; exit 2 ;; esac
grep -Eqs '"react-native"[[:space:]]*:' "$work/package.json" || { step launch false "package.json does not list react-native"; exit 1; }

echo "npm install (React Native and its native modules; several minutes on a first run)"
( cd "$work" && npm install --no-audit --no-fund ) > "$out/npm-install.log.raw" 2>&1 \
  || { step launch false "npm install failed in the project (npm-install.log)"; exit 1; }

signin_form="$(bash "$RT_HERE/lib/signin-form.sh" rn "$work")"
text=""
if [ "$signin_form" != 1 ]; then
  entry="$(bash "$RT_HERE/lib/rn-app.sh" entry "$work")" \
    || { step sign-in false "no index.js (or index.ts, index.tsx, index.jsx) at the project root to add the sign-in hook to"; exit 1; }
  login="$(bash "$RT_HERE/lib/rn-app.sh" login "$work")" \
    || { step sign-in false "no sign-in form and no exported onLoginSucceeded(userId) for the harness to sign in with"; exit 1; }
  app_entry="__rt_app_entry.${entry##*.}"
  mv "$work/$entry" "$work/$app_entry"
  # the user ID is generated by run.sh from [a-z0-9-] only, so it is safe inside the quotes
  {
    echo "// Runtime harness entry, added to a copy of the app (never to the project). It runs the app's own"
    echo "// entry, then signs user A in the way the app's sign-in would: by calling its onLoginSucceeded."
    echo "import './${app_entry%.*}';"
    echo "import { onLoginSucceeded } from './${login%.*}';"
    echo ""
    echo "setTimeout(() => {"
    echo "  Promise.resolve(onLoginSucceeded('$RT_USER_A')).catch((e) => console.error('[runtime harness] onLoginSucceeded failed:', e));"
    echo "}, 2000);"
  } > "$work/$entry"
  # no double quotes or dollar signs: the Android test puts this text into a Kotlin string
  text="onLoginSucceeded(userId) in $login, called by the harness entry 2 s after the app's entry ran"
fi
export RT_RN=1 RT_RN_SIGNIN_FORM="$signin_form" RT_RN_SIGNIN_TEXT="$text"
echo "react-native ($RT_PLATFORM) | sign-in: $([ "$signin_form" = 1 ] && echo "the app's own form" || echo "$text")"

case "$RT_PLATFORM" in
  ios) exec bash "$RT_HERE/hosts/ios.sh" ;;
  android) exec bash "$RT_HERE/hosts/android.sh" ;;
esac
